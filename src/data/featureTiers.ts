/**
 * Lugares geográficos (Fase 6b): qué accidentes entran al juego, con su nombre ES/EN, su tipo, su nivel y de
 * dónde sale su geometría en Natural Earth (dominio público, 1:50m / 1:10m). Editar aquí y correr
 * `node scripts/build-features.mjs --ne <carpeta con los GeoJSON>`, que regenera src/data/featureCatalog.ts,
 * src/data/featureShapes.json y supabase/seed/feature_places.sql (ver la cabecera del script).
 *
 * Niveles pensados para un jugador latinoamericano: Turista (los que casi todos conocen) · Rookie · Crack ·
 * Leyenda. Los países-isla (Madagascar, Cuba, Islandia…) no van: ya están en Banderas. La Antártida no se
 * juega (el mapa termina en 62° S).
 *
 * Geometría: polígonos (mares, lagos, desiertos, cordilleras, islas…) → "dentro" vale cercanía perfecta y fuera
 * cuenta la distancia al borde; líneas (ríos, estrechos angostos) → distancia al punto más cercano; puntos (picos,
 * volcanes, cabos, cataratas) → distancia al punto, como las ciudades.
 */
import type { Difficulty, GameMode, FeatureType } from './cities';

/** [lonMin, latMin, lonMax, latMax] */
export type BBox = [number, number, number, number];

export interface FeatureSpec {
  id: string;
  type: FeatureType;
  tier: Difficulty;
  es: string;
  en: string;
  /** Geometría en Natural Earth (nombre exacto del campo name/NAME, sin distinguir mayúsculas ni acentos) */
  ne?: { ds: 'rivers' | 'rivers10' | 'lakes' | 'lakes10' | 'marine' | 'regions' | 'points' | 'countries'; name: string | string[]; bbox?: BBox };
  /** Coordenadas a mano [lat, lon] (picos, volcanes…), o respaldo si Natural Earth no trae el lugar */
  point?: [number, number];
  /** Región del juego; si falta se calcula por el punto representativo (mares: siempre explícita) */
  region?: GameMode | null;
  /** Packs de país (Fase 7) en los que aparece, con su nivel ahí (p. ej. el Magdalena es Turista en Colombia) */
  packs?: Partial<Record<PackId, Difficulty>>;
  /** Solo en sus packs, nunca en Mundo ni en los continentes (lugares conocidos solo localmente) */
  packOnly?: true;
}

/** Packs de país (Fase 7); hoy solo Colombia */
export type PackId = 'colombia';

type Ne = NonNullable<FeatureSpec['ne']>;
const R = (name: string | string[], bbox?: BBox): Ne => ({ ds: 'rivers', name, bbox });
const R10 = (name: string | string[], bbox?: BBox): Ne => ({ ds: 'rivers10', name, bbox });
const L = (name: string | string[]): Ne => ({ ds: 'lakes', name });
const L10 = (name: string | string[]): Ne => ({ ds: 'lakes10', name });
const M = (name: string | string[]): Ne => ({ ds: 'marine', name });
const G = (name: string | string[], bbox?: BBox): Ne => ({ ds: 'regions', name, bbox });
const P = (name: string | string[], bbox?: BBox): Ne => ({ ds: 'points', name, bbox });
const C = (name: string | string[]): Ne => ({ ds: 'countries', name });
const pt = (lat: number, lon: number): Pick<FeatureSpec, 'point'> => ({ point: [lat, lon] });

const f = (id: string, type: FeatureType, tier: Difficulty, es: string, en: string, ne?: Ne, extra: Partial<FeatureSpec> = {}): FeatureSpec =>
  ({ id, type, tier, es, en, ...(ne ? { ne } : {}), ...extra });

